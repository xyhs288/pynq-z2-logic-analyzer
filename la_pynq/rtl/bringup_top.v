// =====================================================================
//  bringup_top.v -- 板级开机自检（零外接器件版）
//
//  【本版本不需要任何杜邦线、不需要任何外接电路】
//  所有测试信号都在芯片内部产生，全部结果用板载 4 个 LED 显示。
//
//  能验证的三件事：
//    1. 板载 125 MHz 时钟（H16）在【未启动 Linux】时到底存不存在、频率对不对
//    2. 分频链路是否正常
//    3. 三级同步 + 上升沿检测逻辑是否可用（这是后续 trig_fsm 的前置能力）
//
//  暂时验证不了、必须等杜邦线到货才能测的：
//    - Pmod 输入引脚能不能读到【真实外部电平】
//    - 真实异步信号的同步效果
//  （代码里已把 pmod_out / pmod_in 两根线预留好，杜邦线到了不用改代码，
//    只要把 Pmod A 的 pin 1 与 pin 3 短接即可，届时 LED3 会与 LED0 同步闪烁）
//
//  四个 LED 的含义：
//    LED0 = 1 Hz   心跳          -> 时钟活着
//    LED1 = 4 Hz   心跳          -> 时钟够快、分频链正常
//    LED2 = 0.5 Hz 边沿检测指示  -> 同步器 + 上升沿检测逻辑正确
//    LED3 = Pmod 输入电平        -> 现在应为【灭】（引脚内部下拉）
// =====================================================================

module bringup_top (
    input  wire       sys_clk,   // 125 MHz, 引脚 H16
    output wire [3:0] led,       // R14 / P14 / N16 / M14，高电平点亮
    output wire       pmod_out,  // Pmod A pin 1 = Y18（暂时空接，杜邦线到货后使用）
    input  wire       pmod_in    // Pmod A pin 3 = Y16（暂时悬空，内部下拉）
);

    // -----------------------------------------------------------------
    // 1. 上电复位
    //    rst_cnt 从 0 数到 4095 才释放复位，保证所有寄存器从确定
    //    状态开始。125 MHz 下约 33 微秒。
    // -----------------------------------------------------------------
    reg [11:0] rst_cnt = 12'd0;
    wire       rst_n   = (rst_cnt == 12'd4095);

    always @(posedge sys_clk) begin
        if (!rst_n)
            rst_cnt <= rst_cnt + 12'd1;
    end

    // -----------------------------------------------------------------
    // 2. 1 Hz 分频器
    //    125 MHz / 2 / 62_500_000 = 1 Hz，即每 0.5 秒翻转一次。
    //    计到 62_499_999（共 62.5M 拍）翻转，占空比 50%。
    //
    //    【LED0 显示的就是它】。它在闪 = 125 MHz 时钟存在。
    //    它还有第二个用途：作为内部环回的"模拟被测信号"。
    // -----------------------------------------------------------------
    reg [25:0] cnt_1hz = 26'd0;
    reg        sig_1hz = 1'b0;

    always @(posedge sys_clk) begin
        if (!rst_n) begin
            cnt_1hz <= 26'd0;
            sig_1hz <= 1'b0;
        end
        else if (cnt_1hz == 26'd62_499_999) begin
            cnt_1hz <= 26'd0;
            sig_1hz <= ~sig_1hz;
        end
        else begin
            cnt_1hz <= cnt_1hz + 26'd1;
        end
    end

    // -----------------------------------------------------------------
    // 3. 4 Hz 分频器
    //    125 MHz / 2 / 15_625_000 = 4 Hz，即每 0.125 秒翻转一次。
    //    LED1 显示它。如果 LED1 明显比 LED0 快，说明分频链路正常。
    // -----------------------------------------------------------------
    reg [23:0] cnt_4hz = 24'd0;
    reg        sig_4hz = 1'b0;

    always @(posedge sys_clk) begin
        if (!rst_n) begin
            cnt_4hz <= 24'd0;
            sig_4hz <= 1'b0;
        end
        else if (cnt_4hz == 24'd15_624_999) begin
            cnt_4hz <= 24'd0;
            sig_4hz <= ~sig_4hz;
        end
        else begin
            cnt_4hz <= cnt_4hz + 24'd1;
        end
    end

    // -----------------------------------------------------------------
    // 4. 内部环回：三级同步器
    //    把 sig_1hz 当作"模拟的外部信号"送进来，完整走一遍同步流程。
    //
    //    为什么要三级而不是两级：第 1 级 lb_d0 的输入是异步的、可能
    //    进入亚稳态，所以【逻辑上只用 lb_d1】；lb_d2 用来保存 lb_d1
    //    的上一拍，做边沿检测。
    //
    //    注意：sig_1hz 和 sys_clk 本来就是同源的，所以这一轮测的是
    //    【代码逻辑对不对】，不是【真实异步信号的同步效果】。后者
    //    必须等杜邦线接上真实外部信号才能测。
    // -----------------------------------------------------------------
    reg lb_d0 = 1'b0;
    reg lb_d1 = 1'b0;
    reg lb_d2 = 1'b0;

    always @(posedge sys_clk) begin
        lb_d0 <= sig_1hz;
        lb_d1 <= lb_d0;
        lb_d2 <= lb_d1;
    end

    // -----------------------------------------------------------------
    // 5. 上升沿检测
    //    lb_d1 现在为 1 且上一拍 lb_d2 为 0，就是一个上升沿。
    //    这一行就是将来 trig_fsm 里判断触发的核心表达式。
    // -----------------------------------------------------------------
    wire lb_rise = lb_d1 & ~lb_d2;

    // 每检测到一个上升沿计数 +1；LED2 取计数的次低位，
    // 也就是每 2 个上升沿翻转一次 -> 周期 2 秒 = 0.5 Hz。
    // 特意选 0.5 Hz 而不是 1 Hz，是为了让 LED2 和 LED0 肉眼可分。
    reg [1:0] edge_cnt = 2'd0;

    always @(posedge sys_clk) begin
        if (!rst_n)
            edge_cnt <= 2'd0;
        else if (lb_rise)
            edge_cnt <= edge_cnt + 2'd1;
    end

    // -----------------------------------------------------------------
    // 6. Pmod 输入采样（为杜邦线到货后准备）
    //    现在引脚悬空、且 XDC 里设了内部下拉，所以 pin_d1 恒为 0，
    //    LED3 应当是【灭】的。
    //    等接上杜邦线（pin1 短接到 pin3）之后，LED3 会跟着 LED0 同步闪。
    // -----------------------------------------------------------------
    reg pin_d0 = 1'b0;
    reg pin_d1 = 1'b0;

    always @(posedge sys_clk) begin
        pin_d0 <= pmod_in;
        pin_d1 <= pin_d0;
    end

    // -----------------------------------------------------------------
    // 7. 输出
    // -----------------------------------------------------------------
    assign led[0] = sig_1hz;      // 1 Hz   心跳
    assign led[1] = sig_4hz;      // 4 Hz   心跳
    assign led[2] = edge_cnt[1];  // 0.5 Hz 边沿检测指示
    assign led[3] = pin_d1;       // Pmod 输入电平

    // Pmod A pin 1 输出 1 Hz 方波。
    // 现在没有线，这个信号出不去；杜邦线到货后短接到 pin 3，
    // 就能构成一条真实的引脚环回通路，LED3 会与 LED0 同步。
    assign pmod_out = sig_1hz;

endmodule
